  DEPENDENCY_COUNT NUMBER,
  VULNERABILITY_STATUS STRING,
  OPEN_ALERT_COUNT NUMBER,
  REPOSITORY_RISK_SCORE FLOAT,
  RAW VARIANT,
  SCANNED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

