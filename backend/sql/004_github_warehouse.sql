  SCAN_ID STRING NOT NULL,
  REPO_NAME STRING NOT NULL,
  ALERT_NUMBER NUMBER,
  GHSA_ID STRING,
  CLASSIFICATION STRING,
  SEVERITY STRING,
  PACKAGE_NAME STRING,
  STATE STRING,
  RAW VARIANT,
  OBSERVED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS GITHUB_REPOSITORY_EVENTS (
  EVENT_ID STRING NOT NULL,
  REPO_NAME STRING NOT NULL,
  EVENT_TYPE STRING NOT NULL,
  ACTOR_LOGIN STRING,
  ACTION STRING,
  MEMBER_LOGIN STRING,
  EVENT_CREATED_AT TIMESTAMP_TZ NOT NULL,
  SOURCE STRING NOT NULL,
  PAYLOAD VARIANT,
  INGESTED_AT TIMESTAMP_TZ DEFAULT CURRENT_TIMESTAMP()
